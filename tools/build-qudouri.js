// Builds data/qudouri.js from the OpenITI copy of Mukhtasar al-Quduri (Shamela, ed. Kamil Uwaida; unvocalized).
// Each «كتاب» and «باب» heading starts a chapter; paragraphs are the units. A short lead-in paragraph
// (ending with a colon, or a few words) is joined to the paragraph after it.
// usage: node build-qudouri.js <0428AbuHusaynQuduri.Mukhtasar...-ara1> <out file>
const fs = require('fs');
const [src, out] = process.argv.slice(2);
const lines = fs.readFileSync(src, 'utf8').split('\n').filter(l => !l.startsWith('#META'));
const clean = s => s.replace(/PageV\d+P\d+/g, '').replace(/\bms\d+\b/g, '').replace(/\(¬\d+\)/g, '').replace(/¬/g, '').replace(/\s+/g, ' ').trim();
const chapters = [];
let group = null, cur = null;
for (const l of lines) {
  if (/^### /.test(l)) {
    const title = clean(l.replace(/^###\s*\|+\s*(AUTO\s*)?/, '').replace(/^[0-9٠-٩]+\s*-\s*/, ''));
    if (/^كتاب/.test(title)) group = title;
    cur = { title, group, paras: [] };
    chapters.push(cur);
    continue;
  }
  if (!cur) continue;
  if (/^# /.test(l)) cur.paras.push(l.slice(2));
  else if (/^~~/.test(l) && cur.paras.length) cur.paras[cur.paras.length - 1] += ' ' + l.slice(2);
}
const ar = n => String(n).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[d]);
const book = chapters.map((c, ci) => {
  const units = [];
  let carry = '';
  for (const p0 of c.paras) {
    const p = clean(p0); if (!p) continue;
    const text = carry ? carry + ' ' + p : p;
    if (/:\s*$/.test(p) || p.split(' ').length < 4) { carry = text; continue; }
    carry = '';
    units.push(text);
  }
  if (carry) units.length ? units[units.length - 1] += ' ' + carry : units.push(carry);
  return { id: 'q' + (ci + 1), title: c.title, group: c.group === c.title ? c.title : c.group,
    units: units.map((t, k) => ({ id: 'q' + (ci + 1) + '_' + (k + 1), label: c.title + ' · الفقرة ' + ar(k + 1), segs: [['matn', t]] })) };
}).filter(c => c.units.length);
const BOOK = { key: 'qudouri', app: 'mutoon', lsk: 'mutoon_qudouri_v1', title: 'مختصر القدوري',
  sub: 'في فقه الإمام أبي حنيفة · أبو الحسين القدوري (ت ٤٢٨هـ) · ' + ar(book.length) + ' بابًا', unitWord: 'فقرة', chapters: book };
fs.writeFileSync(out, '// Generated by tools/build-qudouri.js from OpenITI 0428AbuHusaynQuduri.Mukhtasar (Shamela, ed. Kamil Uwaida)\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
const n = book.reduce((a, c) => a + c.units.length, 0);
console.log('chapters', book.length, 'units', n, 'longest', Math.max(...book.flatMap(c => c.units.map(u => u.segs[0][1].split(' ').length))));
