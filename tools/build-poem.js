// Builds a one-poem data file from a text file: «## title» starts a section, every other line is «first hemistich | second».
// usage: node tools/build-poem.js <text file> <key> '<json of the book's fields>'
//   fields: title, sub (verse count appended), nazim, death, meter, source, srcUrl, note
const fs = require('fs'), path = require('path');
const [src, key, meta] = process.argv.slice(2);
const M = JSON.parse(meta);
const verses = [], secs = {};
for (const l of fs.readFileSync(src, 'utf8').split('\n').map(x => x.trim()).filter(Boolean)) {
  if (l.startsWith('## ')) { secs[verses.length + 1] = l.slice(3); continue; }
  const [a, b, extra] = l.split(' | ');
  if (!b || extra !== undefined) throw new Error('needs exactly one « | »: ' + l);
  verses.push([a.trim(), b.trim()]);
}
const ar = n => String(n).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[d]);
const BOOK = { key, app: 'mutoon-' + key, lsk: 'mutoon_' + key + '_v1', prefix: key.slice(0, 2) + '_', title: M.title,
  sub: M.sub + ' · ' + ar(verses.length) + ' بيتًا',
  poems: [{ id: key, title: M.title, nazim: M.nazim, death: M.death, meter: M.meter || 'الرجز', source: M.source, srcUrl: M.srcUrl || '', note: M.note || '', verses, secs: Object.keys(secs).length ? secs : { 1: M.title } }] };
const out = path.join(__dirname, '..', 'data', key + '.js');
fs.writeFileSync(out, '// Generated by tools/build-poem.js from ' + path.basename(src) + ' — edit that file, not this one\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
console.log(key, 'verses', verses.length, 'sections', Object.keys(secs).length);
