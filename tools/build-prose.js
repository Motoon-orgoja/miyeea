// Builds prose data files for the prose engine from the collected texts:
//   nawawi:      one chapter per hadith; a long hadith is cut into passages of about 35 words at sentence ends
//   ajurrumiyya: one chapter per bab; its paragraphs are the units (a very short one joins the next)
// usage: node tools/build-prose.js <nawawi|ajurrumiyya> <json file>
const fs = require('fs'), path = require('path');
const [kind, src] = process.argv.slice(2);
const J = JSON.parse(fs.readFileSync(src, 'utf8'));
const ar = n => String(n).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[d]);
const words = t => t.split(/\s+/).filter(Boolean).length;
// cut at sentence or clause ends (. ، ؛ : ؟ !) into pieces near `size` words
function chunks(text, size) {
  const parts = text.match(/[^.،؛:؟!]+[.،؛:؟!]*\s*/g) || [text], out = [];
  let cur = '';
  for (const p of parts) { if (cur && words(cur) + words(p) > size) { out.push(cur.trim()); cur = '' } cur += p }
  if (cur.trim()) out.push(cur.trim());
  // a tiny tail joins the piece before it
  if (out.length > 1 && words(out[out.length - 1]) < 8) out[out.length - 2] += ' ' + out.pop();
  return out;
}
let BOOK;
if (kind === 'nawawi') {
  const chapters = J.hadiths.map(h => {
    const id = 'n' + h.n, pieces = chunks(h.matn.trim(), 35);
    const units = pieces.map((m, k) => {
      const segs = []; if (k === 0 && h.rawi) segs.push(['rawi', h.rawi.trim()]); segs.push(['matn', m]);
      if (k === pieces.length - 1 && h.takh) segs.push(['takh', h.takh.trim()]);
      return { id: id + '_' + (k + 1), label: 'الحديث ' + ar(h.n) + (pieces.length > 1 ? ' · المقطع ' + ar(k + 1) + ' من ' + ar(pieces.length) : ''), segs };
    });
    const g = Math.floor((h.n - 1) / 10) * 10;
    return { id, title: 'الحديث ' + ar(h.n) + ': ' + h.title, group: 'الأحاديث ' + ar(g + 1) + '–' + ar(Math.min(g + 10, J.hadiths.length)), units };
  });
  BOOK = { key: 'nawawi', app: 'mutoon', lsk: 'mutoon_nawawi_v1', title: 'الأربعون النووية', unitWord: 'حديث',
    sub: 'الإمام يحيى بن شرف النووي (ت ٦٧٦هـ) · ' + ar(J.hadiths.length) + ' حديثًا', source: J.source, chapters };
} else if (kind === 'ajurrumiyya') {
  const chapters = J.chapters.map((c, ci) => {
    const paras = []; let carry = '';
    for (const p0 of c.paras) { const p = (carry ? carry + ' ' : '') + p0.trim(); if (words(p) < 6) { carry = p; continue } carry = ''; paras.push(p) }
    if (carry) paras.length ? paras[paras.length - 1] += ' ' + carry : paras.push(carry);
    return { id: 'a' + (ci + 1), title: c.title, units: paras.map((t, k) => ({ id: 'a' + (ci + 1) + '_' + (k + 1), label: c.title + ' · ' + ar(k + 1), segs: [['matn', t]] })) };
  });
  BOOK = { key: 'ajurrumiyya', app: 'mutoon', lsk: 'mutoon_ajurrumiyya_v1', title: 'متن الآجرومية', unitWord: 'فقرة',
    sub: 'في النحو · ابن آجروم الصنهاجي (ت ٧٢٣هـ) · ' + ar(chapters.length) + ' بابًا', source: J.source, chapters };
} else throw new Error('kind?');
const out = path.join(__dirname, '..', 'data', BOOK.key + '.js');
fs.writeFileSync(out, '// Generated by tools/build-prose.js — edit the source text, not this file\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
console.log(BOOK.key, 'chapters', BOOK.chapters.length, 'units', BOOK.chapters.reduce((n, c) => n + c.units.length, 0));
