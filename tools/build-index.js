// Builds data/index.js: what the home page needs of every text, without the text itself — the keys where progress is saved,
// the poems with their number of verses, the chapters with their unit ids (and kinds, for tracks). The home page used to load
// every data file (tens of MB once the big hadith books came); now it loads this one small file.
// usage: node tools/build-index.js        (tools/build-matn.js runs it after every build; tools/check.js fails when it is stale)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), P = f => path.join(root, f);

function slim(B) {
  const o = { key: B.key, title: B.title, lsk: B.lsk };
  for (const k of ['prefix', 'unitWord', 'track', 'tracks']) if (B[k] !== undefined) o[k] = B[k];
  if (B.poems) o.poems = B.poems.map(p => ({ id: p.id, title: p.title, n: p.verses.length }));
  else o.chapters = (B.chapters || []).map(c => ({ id: c.id, title: c.title, units: c.units.map(u => u.kind ? { id: u.id, kind: u.kind } : { id: u.id }) }));
  return o;
}
function build() {
  // the texts in the order of the texts sheet (ui.js), each one that has a data file
  const ui = fs.readFileSync(P('ui.js'), 'utf8'), i = ui.indexOf('const BOOKS=['), j = ui.indexOf('\n];', i);
  const keys = [...ui.slice(i, j).matchAll(/key:'([a-z0-9]+)'/g)].map(m => m[1]).filter(k => fs.existsSync(P('data/' + k + '.js')));
  const out = keys.map(k => { const w = {}; new Function('window', fs.readFileSync(P('data/' + k + '.js'), 'utf8'))(w); if (!w.BOOK) throw new Error('data/' + k + '.js: no BOOK'); return slim(w.BOOK); });
  return '// Generated by tools/build-index.js from data/*.js: what the home page needs of every text (no text itself).\nwindow.BOOKS=' + JSON.stringify(out) + ';\n';
}
module.exports = { build };
if (require.main === module) { const s = build(); fs.writeFileSync(P('data/index.js'), s); console.log('data/index.js', (s.length / 1024).toFixed(0) + ' KB'); }
