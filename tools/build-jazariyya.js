// Builds data/jazariyya.js from tools/jazariyya.txt: «## title» starts a section, every other line is «first hemistich | second».
// The text and vocalization follow the edition the user supplied (Al_Jazreyah.pdf), corrected where its marks were wrong;
// the corrections are listed in the page note.
const fs = require('fs'), path = require('path');
const lines = fs.readFileSync(path.join(__dirname, 'jazariyya.txt'), 'utf8').split('\n').map(l => l.trim()).filter(Boolean);
const verses = [], secs = {};
for (const l of lines) {
  if (l.startsWith('## ')) { secs[verses.length + 1] = l.slice(3); continue; }
  const [a, b] = l.split(' | '); if (!b) throw new Error('no hemistich separator: ' + l);
  verses.push([a, b]);
}
const ar = n => String(n).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[d]);
const BOOK = { key: 'jazariyya', app: 'mutoon-jazariyya', lsk: 'mutoon_jazariyya_v1', prefix: 'jz_', title: 'المقدمة الجزرية',
  sub: 'فيما يجب على قارئ القرآن أن يعلمه · ابن الجزري (ت ٨٣٣هـ) · ' + ar(verses.length) + ' بيتًا',
  poems: [{ id: 'jazariyya', title: 'المقدمة الجزرية', nazim: 'شمس الدين محمد بن محمد ابن الجزري', death: 'ت ٨٣٣هـ', meter: 'الرجز',
    source: 'النسخة اللي أرسلها الحافظ (Al_Jazreyah.pdf)، مع تصحيح أخطاء ضبطها', srcUrl: '',
    note: 'نقلت الأبيات وحركاتها من النسخة المرسلة، وصُحّحت فيها مواضع ضبطها غلط (مثل: «بِاللُّطْفِ» مكان «باللفظ»، و«فِرْقٍ»، و«بَسَطْتَ»، و«أَنْ لَا أَقُولَ»، و«وَأَنْ لَمِ … إِنَّ مَا»، و«يَبْلُو»، و«تَأْسَوْا»)، وقُدِّم بيت «فُصِّلَتِ النِّسَا» على بيت «الْأَنْعَامِ» لأن المعنى متصل.',
    verses, secs }] };
fs.writeFileSync(path.join(__dirname, '..', 'data/jazariyya.js'), '// Generated by tools/build-jazariyya.js — edit tools/jazariyya.txt, not this file\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
console.log('verses', verses.length, 'sections', Object.keys(secs).length);
