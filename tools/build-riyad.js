// Builds data/riyad.js — the complete Riyad as-Salihin — from the staged pipeline in tools/riyad/:
//   node tools/riyad-fetch.js shamela140|sunnah|quran …   (cached downloads → tools/riyad-cache/, git-ignored)
//   Word export of the IslamHouse al-Fahl .doc → tools/riyad-cache/ihdoc/fahl.htm
//   node tools/riyad/parse-fahl.js      structure (chapters, books, hadith paragraphs)
//   node tools/riyad/numbering.js       al-Fahl numbers → standard numbers (riyadh.islamenc.com = Dalil al-Falihin = chapter 91)
//   node tools/riyad/build-units.js     units, ayat replaced by the api.quran.com text, long hadiths split
//   node tools/riyad/align-dalil.js units-a.json   locate Dalil al-Falihin passages
//   node tools/riyad/collate.js         collation with sunnah.com + islamenc (+ Dalil), harakat completed from islamenc
//   node tools/riyad/prep-voc.js        orthography + vocalization work files (tools/riyad/voc/in)
//   (vocalization pass → tools/riyad/voc/out, kept in the repo)
//   node tools/riyad/voc-merge.js       merge under strict rules
//   node tools/build-riyad.js           this file: letter corrections, final clean-up, chapter 91 kept as hand-checked
const fs=require('fs'),path=require('path');const {strip,ar,words,ortho}=require('./riyad/lib.js');
const C=path.join(__dirname,'riyad-cache');
const U=JSON.parse(fs.readFileSync(path.join(C,'units-d.json'),'utf8'));
const C91=JSON.parse(fs.readFileSync(path.join(__dirname,'riyad','riyad91-original.json'),'utf8'));
const FIXES=JSON.parse(fs.readFileSync(path.join(__dirname,'riyad','textfix.json'),'utf8'));
const LOG=[];
function replaceStripped(t,from,to){ // replace the stretch whose bare letters/punctuation equal `from`
  const idx=[];let s='';for(let i=0;i<t.length;i++){if(!/[ً-ْٰ]/.test(t[i])){idx.push(i);s+=t[i]}}idx.push(t.length);
  const L=/[ء-ي]/;let k=-1,p=0;
  while((p=s.indexOf(from,p))>=0){if(!(p>0&&L.test(s[p-1])&&L.test(from[0]))&&!(L.test(s[p+from.length]||'')&&L.test(from[from.length-1]))){k=p;break}p++}
  if(k<0)return null;let a=idx[k],b=idx[k+from.length];while(b<t.length&&/[ً-ْٰ]/.test(t[b]))b++;
  return (t.slice(0,a)+to+t.slice(b)).replace(/\s+/g,' ').trim();
}
const byId={};for(const c of U.chapters)for(const u of c.units)byId[u.id]=u;
for(const [id,from,to,why] of FIXES){const u=byId[id];let done=false;
  if(u)for(const s of u.segs){if(done||s[0]==='aya')continue;const r=replaceStripped(s[1],from,to);if(r!=null){LOG.push({id,from,to,why});s[1]=r;done=true}}
  if(!done)LOG.push({id,from,to,why,notApplied:true});}
// «الله عليه وسلم» with «صلى» dropped
const SALLA=/(^|[^ى]\s)(الله عليه وسلم)/g;
function clean(t){
  return ortho(t).replace(/[-‌‍­]/g,'').replace(/([ء-ي][ً-ْ]*)ـ+(?=[ء-ي])/g,'$1')
    .replace(SALLA,(m,a,b)=>{LOG.push({formula:'صلى restored'});return a+'صلى '+b})
    .replace(/\[([^\]]*)\]/g,m=>m.replace(/\d/g,d=>ar(d)).replace(/\s*-\s*/g,'–'))
    .replace(/\s+/g,' ').trim();
}
const units=c=>c.units.map(u=>{const o={id:u.id,kind:u.kind,label:u.label,segs:u.segs.map(([k,t])=>[k,k==='aya'?t:clean(t)]).filter(s=>s[1])};
  if(u.gloss&&u.gloss.length)o.gloss=u.gloss.map(([a,b])=>[clean(a),clean(b)]);return o});
const chapters=[];
chapters.push({id:'riyad0',title:'مقدمة المؤلف',units:U.muq.map((t,k)=>({id:'m'+(k+1),kind:'text',label:'المقدمة · فقرة '+ar(k+1),segs:[['matn',clean(t)]]}))});
for(const c of U.chapters){
  if(c.n===91){chapters.push({id:'riyad91',title:C91.title,group:c.group||'المقدمة',units:C91.units});continue}
  chapters.push({id:'riyad'+c.n,title:c.title.replace(/\s+/g,' ').replace(/\s*\(\)\s*/g,' ').trim(),group:c.group||'المقدمة',units:units(c)});
}
const nCh=chapters.length-1,nH=new Set(chapters.flatMap(c=>c.units.filter(u=>u.kind==='hadith').map(u=>u.id.replace(/[a-z]+$/,'')))).size;
const BOOK={key:'riyad',app:'mutoon',lsk:'mutoon_riyad91_v1',title:'رياض الصالحين',sub:'للإمام النووي · '+ar(nCh)+' بابًا · '+ar(nH)+' حديثًا',unitWord:'حديث',sharhDir:'data/riyad-sharh/',chapters};
const head='// Riyad as-Salihin (al-Nawawi), complete. Generated by tools/build-riyad.js — do not edit by hand.\n'+
 '// Text: al-Fahl edition (IslamHouse), collated with sunnah.com and riyadh.islamenc.com; numbering of riyadh.islamenc.com / Dalil al-Falihin;\n'+
 '// Qur\'an text from api.quran.com; harakat completed and checked (see tools/texts/riyad-collation.md). Chapter 91 is the hand-checked trial chapter.\n';
fs.writeFileSync(path.join(__dirname,'..','data','riyad.js'),head+'window.BOOK='+JSON.stringify(BOOK)+';\n');
fs.writeFileSync(path.join(C,'build-log.json'),JSON.stringify(LOG,null,1));
console.log('chapters',nCh,'(+ preface) hadiths',nH,'units',chapters.reduce((a,c)=>a+c.units.length,0),'letter fixes',LOG.filter(x=>x.id&&!x.notApplied).length,'not applied',LOG.filter(x=>x.notApplied).map(x=>x.id+':'+x.from).join(' | '),'salla restored',LOG.filter(x=>x.formula).length);
