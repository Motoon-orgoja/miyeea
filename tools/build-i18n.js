// Builds i18n/fus.js and i18n/en.js from tools/i18n/tr.json (+ extra.json for strings added by hand).
// usage: node tools/build-i18n.js
const fs=require('fs'),path=require('path'),dir=path.join(__dirname,'i18n'),out=path.join(__dirname,'..','i18n');
const T={...JSON.parse(fs.readFileSync(path.join(dir,'tr.json'),'utf8'))};
const ex=path.join(dir,'extra.json'); if(fs.existsSync(ex))Object.assign(T,JSON.parse(fs.readFileSync(ex,'utf8')));
fs.mkdirSync(out,{recursive:true});
for(const lang of ['fus','en']){
  const D={}; for(const[k,v]of Object.entries(T))if(v&&v[lang]!=null&&v[lang]!==k)D[k]=v[lang];
  fs.writeFileSync(path.join(out,lang+'.js'),'// Generated by tools/build-i18n.js — edit tools/i18n/*.json\nwindow.I18N='+JSON.stringify(D)+';\n');
  console.log(lang,Object.keys(D).length);
}
