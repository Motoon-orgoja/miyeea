// Builds data/shatibiyya.js from Shamela book 7754 («متن الشاطبية منقّح ومصحّح», vocalized, numbered 1–1166 in this edition).
// usage: node fetch-shatibiyya.js <out file>
const https = require('https'), fs = require('fs');
const get = u => new Promise((ok, no) => https.get(u, { headers: { 'User-Agent': 'Mozilla/5.0' } }, r => {
  const b = []; r.on('data', c => b.push(c)); r.on('end', () => ok(Buffer.concat(b).toString('utf8')));
}).on('error', no));
// one entry per <p> of the page text
async function page(p) {
  const d = await get('https://shamela.ws/book/7754/' + p);
  const t = d.slice(d.indexOf('class="nass')).replace(/^[^>]*>/, '').split('id="appended_pages"')[0];
  return t.split(/<p[ >]/).map(b => b.replace(/<a [\s\S]*?<\/a>/g, '').replace(/<[^>]+>/g, '').replace(/^[^>]*>/, '')
    .replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').replace(/<div$/, '').trim()).filter(Boolean);
}
const toInt = s => parseInt(s.replace(/[٠-٩]/g, c => '٠١٢٣٤٥٦٧٨٩'.indexOf(c)), 10);
// the two verses this copy prints without the hemistich marker
const MANUAL = {
  107: ['وَمَهْمَا تَصِلْهَا مَعْ أَوَاخِرِ سُورَةٍ', 'فَلاَ تَقِفَنَّ الدَّهْرَ فِيهاَ فَتَثْقُلَا'],
  444: ['سَأَمْضِي عَلَى شَرْطِي وَبِاللهِ أَكْتَفِي', 'وَمَا خَابَ ذُو جِدٍّ إِذَا هُوَ حَسْبَلَا']
};
(async () => {
  const verses = [], secs = {};
  let pendingSec = null;
  for (let p = 7; p <= 99; p++) {
    for (const l of await page(p)) {
      const m = l.match(/^([٠-٩0-9]+)\s*-\s*(.+)$/);
      if (m) {
        const n = toInt(m[1]);
        if (n !== verses.length + 1) throw new Error('numbering jump: expected ' + (verses.length + 1) + ', got ' + n);
        // a word split across the hemistichs is printed «والْـ ... ... ـملائكة», so treat a run of markers as one
        const v = MANUAL[n] || m[2].split(/\s*(?:\.\.\.\s*)+/).map(x => x.trim());
        if (v.length !== 2) throw new Error('verse ' + n + ' does not split in two: ' + m[2]);
        if (pendingSec) { secs[n] = pendingSec; pendingSec = null; }
        verses.push(v);
        continue;
      }
      if (/^\*/.test(l) || /^بِسْمِ اللَّهِ/.test(l) || /^مَتْنُ الشَّاطِبِيَّةِ/.test(l)) continue;
      // chapter headings: «بَابُ الاسْتِعَاذَةِ (٥)», «(مُقَدِّمَةٌ) (٩٤)», «[(الخاتمة)]» — drop the verse count and brackets
      const title = l.replace(/\s*\([٠-٩0-9]+\)\s*$/, '').replace(/^\[\((.*)\)\]$/, '$1').replace(/^\((.*)\)$/, '$1').replace(/^[ً-ْ]+/, '').trim();
      if (title && title.length < 120) pendingSec = title;
    }
  }
  const BOOK = { key: 'shatibiyya', app: 'mutoon-shatibiyya', lsk: 'mutoon_shatibiyya_v1', prefix: 'sh_', title: 'الشاطبية',
    sub: 'حرز الأماني ووجه التهاني في القراءات السبع · الإمام الشاطبي (ت ٥٩٠هـ) · ' + verses.length.toLocaleString('ar-EG') + ' بيتًا بترقيم هذه النشرة',
    poems: [{ id: 'shatibiyya', title: 'الشاطبية', nazim: 'القاسم بن فيرّه الشاطبي', death: 'ت ٥٩٠هـ', meter: 'الطويل',
      source: 'المكتبة الشاملة: متن الشاطبية (منقّح ومصحّح)', srcUrl: 'https://shamela.ws/book/7754',
      note: 'النص المشكول من نشرة «متن الشاطبية منقّح ومصحّح» على المكتبة الشاملة، وعدد أبياتها بترقيمها ١١٦٦ بيتًا (والمشهور ١١٧٣ بعدّ آخر). فُصل شطرا البيتين ١٠٧ و٤٤٤ يدويًا لأنهما وردا بلا فاصل.',
      verses, secs }] };
  fs.writeFileSync(process.argv[2], '// Generated by tools/fetch-shatibiyya.js from shamela.ws/book/7754\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
  console.log('verses', verses.length, 'sections', Object.keys(secs).length);
  console.log(Object.entries(secs).map(([k, v]) => k + ':' + v).join('\n'));
})().catch(e => { console.error(e); process.exit(1); });
