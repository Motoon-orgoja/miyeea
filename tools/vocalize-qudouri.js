// Puts the corrected, vocalized Quduri text into data/qudouri.js, keeping every chapter and unit id (so saved progress stays).
// The text in tools/qudouri-voc/chunkN.json was collated word by word against the matn printed in «التصحيح والترجيح»
// (ed. Diya Yunus, Dar al-Kutub al-Ilmiyya; Shamela 985), corrected where the typed Shamela copy had typos or dropped
// words, and fully vocalized. Each chunk logs its letter changes ("changes") and open questions ("doubts").
// usage: node tools/vocalize-qudouri.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), file = path.join(root, 'data/qudouri.js');
const src = fs.readFileSync(file, 'utf8');
const BOOK = JSON.parse(src.slice(src.indexOf('window.BOOK=') + 12, src.lastIndexOf(';')));
const voc = {};
fs.readdirSync(path.join(__dirname, 'qudouri-voc')).filter(f => /^chunk\d+\.json$/.test(f))
  .forEach(f => Object.assign(voc, JSON.parse(fs.readFileSync(path.join(__dirname, 'qudouri-voc', f), 'utf8')).units));
// final review: keep the honorifics our text had where the other edition drops or shortens them, keep the Quranic
// «وعشر» in the waiting period, and drop numbering left in two headings
const FIX = [
  ['q20_1', 'أَبُو حَنِيفَةَ:', 'أَبُو حَنِيفَةَ رَحِمَهُ اللَّهُ:'],
  ['q34_1', 'أَبُو حَنِيفَةَ:', 'أَبُو حَنِيفَةَ رَحِمَهُ اللَّهُ تَعَالَى:'],
  ['q23_12', 'النَّبِيِّ عَلَيْهِ السَّلَامُ', 'النَّبِيِّ صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ'],
  ['q34_3', 'النَّبِيِّ عَلَيْهِ السَّلَامُ', 'النَّبِيِّ صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ'],
  ['q39_19', 'النَّبِيِّ عَلَيْهِ السَّلَامُ', 'النَّبِيِّ صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ'],
  ['q113_57', 'بِإِجْمَاعِ الصَّحَابَةِ', 'بِإِجْمَاعِ الصَّحَابَةِ رَضِيَ اللَّهُ عَنْهُمْ'],
  ['q88_3', 'أَرْبَعَةُ أَشْهُرٍ وَعَشَرَةُ أَيَّامٍ', 'أَرْبَعَةُ أَشْهُرٍ وَعَشْرٌ'],
  ['q89_29', '43 - ', ''],
  ['q117_17', '1 - ', ''],
];
FIX.forEach(([id, a, b]) => { if (!voc[id] || !voc[id].includes(a)) throw new Error('fix not found: ' + id + ' ' + a); voc[id] = voc[id].replace(a, b) });
let n = 0, miss = [];
BOOK.chapters.forEach(c => c.units.forEach(u => { const v = voc[u.id]; if (v) { u.segs = [['matn', v.trim()]]; n++ } else miss.push(u.id) }));
if (miss.length) throw new Error('no vocalized text for ' + miss.length + ' units, e.g. ' + miss.slice(0, 5).join(' '));
BOOK.vocalized = true;
fs.writeFileSync(file, '// Generated by tools/build-qudouri.js, then corrected and vocalized by tools/vocalize-qudouri.js\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
console.log('vocalized units', n);
