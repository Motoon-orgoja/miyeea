// Builds a text collected by NEW-BRIEF.md (tools/texts/<key>.txt or .json + <key>.meta.json) into data/<key>.js,
// and on first build registers it on the site (tools/register-book.js).
//   poem  (.txt):  through build-poem.js
//   prose (.json): chapters of paragraphs, or of hadiths {rawi, matn, takh}; a long hadith is cut at clause ends like the Nawawi
// usage: node tools/build-matn.js <key> [--no-register]
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const root = path.join(__dirname, '..'), T = f => path.join(root, 'tools/texts', f);
const key = process.argv[2], noReg = process.argv.includes('--no-register');
const M = JSON.parse(fs.readFileSync(T(key + '.meta.json'), 'utf8').replace(/^﻿/, ''));
const ar = n => String(n).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[d]);
const words = t => t.split(/\s+/).filter(Boolean).length;
let kind, count;
if (fs.existsSync(T(key + '.txt'))) {
  kind = 'poem';
  const out = execFileSync('node', [path.join(__dirname, 'build-poem.js'), T(key + '.txt'), key, JSON.stringify(M)], { encoding: 'utf8' });
  process.stdout.write(out); count = ar(+out.match(/verses (\d+)/)[1]) + ' بيتًا';
} else {
  kind = 'prose';
  const J = JSON.parse(fs.readFileSync(T(key + '.json'), 'utf8').replace(/^﻿/, ''));
  function chunks(text, size) {
    const parts = text.match(/[^.،؛:؟!]+[.،؛:؟!]*\s*/g) || [text], out = [];
    let cur = '';
    for (const p of parts) { if (cur && words(cur) + words(p) > size) { out.push(cur.trim()); cur = '' } cur += p }
    if (cur.trim()) out.push(cur.trim());
    if (out.length > 1 && words(out[out.length - 1]) < 8) out[out.length - 2] += ' ' + out.pop();
    return out;
  }
  const P = key.slice(0, 2); let hn = 0;
  // the author's own word glosses after a hadith (gharib) are read, not memorised: they go to the chapter's commentary file
  const SH = {};
  // the author's introduction (intro: paragraphs) is the first chapter
  // (only when it is vocalized: an unvocalized one cannot be memorised reliably)
  const voc = t => (t.match(/[ً-ْ]/g) || []).length / Math.max(1, t.replace(/[^ء-ي]/g, '').length);
  if (J.intro && J.intro.length && voc(J.intro.join(' ')) > 0.4) J.chapters.unshift({ title: 'مقدمة المؤلف', paras: J.intro.filter(p => !/^بِسْمِ اللَّهِ/.test(p)) });
  const chapters = J.chapters.map((c, ci) => {
    const id = P + (ci + 1), units = [];
    if (c.hadiths) c.hadiths.forEach(h => {
      hn++; const num = h.label || (h.n ? ar(h.n) : ar(hn)); const pieces = chunks(h.matn.trim(), 35);
      pieces.forEach((m, k) => {
        const segs = []; if (k === 0 && h.rawi) segs.push(['rawi', h.rawi.trim()]); segs.push(['matn', m]);
        if (k === pieces.length - 1 && h.takh) segs.push(['takh', h.takh.trim()]);
        units.push({ id: id + '_' + (units.length + 1), label: 'الحديث ' + num + (pieces.length > 1 ? ' · المقطع ' + ar(k + 1) + ' من ' + ar(pieces.length) : ''), segs });
      });
      if (h.gharib) (SH[id] = SH[id] || {})[units[units.length - 1].id] = { title: '📘 الغريب من كلام المؤلف', foot: '',
        secs: [{ src: M.title + ' · ' + M.nazim, text: h.gharib.trim() }] };
    });
    else {
      // a very short paragraph joins the next one
      const paras = []; let carry = '';
      // a long paragraph is cut at clause ends, like a long hadith
      for (const p0 of c.paras.flatMap(p => words(p) > 45 ? chunks(p, 30) : [p])) { const p = (carry ? carry + ' ' : '') + p0.trim(); if (words(p) < 6) { carry = p; continue } carry = ''; paras.push(p) }
      if (carry) paras.length ? paras[paras.length - 1] += ' ' + carry : paras.push(carry);
      paras.forEach((t, k) => units.push({ id: id + '_' + (k + 1), label: c.title + ' · ' + ar(k + 1), segs: [['matn', t]] }));
    }
    const ch = { id, title: c.title, units }; if (c.group) ch.group = c.group; return ch;
  });
  const hadith = J.chapters.some(c => c.hadiths);
  count = hadith ? ar(hn) + ' حديثًا' : ar(chapters.length) + ' بابًا';
  const BOOK = { key, app: 'mutoon', lsk: 'mutoon_' + key + '_v1', title: M.title, unitWord: hadith ? 'حديث' : 'فقرة',
    sub: M.sub + ' · ' + count, source: J.source + (J.check ? ' · قوبل بـ: ' + J.check : ''), note: M.note || '', chapters };
  if (J.basmala) BOOK.basmala = J.basmala;
  // a beginner's explanation of each chapter (tools/texts/explain/BRIEF.md): plain intro, one explanation per unit, tree, quiz
  require('./explain-layer.js')(key, chapters, SH);
  const shDir = path.join(root, 'data', key + '-sharh');
  // every chapter gets a file (the page asks for each chapter's), or the book says it has none
  if (Object.keys(SH).length) { fs.mkdirSync(shDir, { recursive: true }); for (const c of chapters) fs.writeFileSync(path.join(shDir, c.id + '.json'), JSON.stringify(SH[c.id] || {})) }
  else BOOK.sharh = false;
  fs.writeFileSync(path.join(root, 'data', key + '.js'), '// Generated by tools/build-matn.js from tools/texts/' + key + '.json — edit that file, not this one\nwindow.BOOK=' + JSON.stringify(BOOK) + ';\n');
  console.log(key, 'chapters', chapters.length, 'units', chapters.reduce((n, c) => n + c.units.length, 0), hadith ? 'hadiths ' + hn : '');
}
const ui = fs.readFileSync(path.join(root, 'ui.js'), 'utf8');
if (!noReg && !ui.includes(`key:'${key}'`)) {
  const d = (M.d || M.c) + (M.d && /[٠-٩]/.test(M.d) ? '' : ' · ' + count);
  console.log(execFileSync('node', [path.join(__dirname, 'register-book.js'), key, kind, M.title, d, '', M.c || ''], { encoding: 'utf8' }));
}
